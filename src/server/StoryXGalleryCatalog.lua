local byId = {}
for _,entry in ipairs(Catalog.entries) do
    assert(not byId[entry.id],"Duplicate exhibition id")
    assert(entry.correct>=1 and entry.correct<=#entry.options,"Invalid quiz key")
    byId[entry.id]=entry
end
function Catalog.get(id)
    return type(id)=="string" and byId[id] or nil
end
function Catalog.public(entry)
    if not entry then return nil end
    return {
        id=entry.id,title=entry.title,subtitle=entry.subtitle,scene=entry.scene,
        reflection=entry.reflection,question=entry.question,
        options=entry.options,link=entry.link,
    }
end
function Catalog.verify(id,choice)
    local entry=Catalog.get(id)
    return entry~=nil and type(choice)=="number" and choice%1==0
        and choice==entry.correct
end
return Catalog
